#!/usr/bin/env node
/**
 * Aether — generate ATTRIBUTION.md from the data-source contract.
 *
 * Attribution obligations survive the personal-use carve-out: CC BY attaches to *display of
 * the data*, not to distribution of the code. ECMWF's exact service wording is a legal
 * requirement even in a private app.
 *
 * Generating this file from `sources.mjs` rather than hand-maintaining it means a new data
 * source cannot ship without its attribution string. `--check` fails CI if the two drift.
 *
 * Usage:
 *   node scripts/gen-attribution.mjs           # write ATTRIBUTION.md
 *   node scripts/gen-attribution.mjs --check   # exit 1 if out of date
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { SOURCES, requiredAttributions } from '../src/data/sources.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, '..', 'ATTRIBUTION.md');
const check = process.argv.includes('--check');

const attributions = requiredAttributions();
const noAttribution = SOURCES.filter((s) => !s.attribution);

const lines = [
  '# Data source attributions',
  '',
  '<!-- GENERATED by scripts/gen-attribution.mjs — do not edit by hand. -->',
  '<!-- Regenerate with: pnpm attribution -->',
  '',
  'Every string below must be displayed in the app on the **Data Sources** screen.',
  'These obligations are **not** waived by the personal-use scope — CC BY attaches to display',
  'of the data itself, regardless of whether the software is ever distributed.',
  '',
  `${attributions.length} sources require attribution; ${noAttribution.length} do not.`,
  '',
  '## Required',
  '',
  '| Source | Display string | License |',
  '|---|---|---|',
];

for (const a of attributions) {
  const text = a.url ? `${a.text} (link to ${a.url})` : a.text;
  lines.push(`| ${a.name} | **${text}** | ${a.license} |`);
}

lines.push(
  '',
  '## No attribution legally required',
  '',
  'Displayed anyway as provenance — the Data Sources screen is part of the trust identity.',
  '',
);
for (const s of noAttribution) {
  lines.push(`- **${s.name}** — ${s.license}`);
}

lines.push(
  '',
  '## Standing obligations that are not just a string',
  '',
  '- **ECMWF** — the exact wording *"This service is based on data and products of ECMWF"*,',
  '  plus `© [year] ECMWF`, the CC BY 4.0 link, and a note of any modifications made.',
  '- **SondeHub (CC BY-SA 2.0)** — share-alike is active. Display sonde data *alongside* model',
  '  data; never blend them into a derived product. Any exported sonde archive is relicensed',
  '  CC BY-SA 2.0.',
  '- **MET Norway** — an identifying `User-Agent` is mandatory, and the name "Yr" may not appear',
  '  in the app name. "Aether" complies.',
  '- **NWS / api.weather.gov** — descriptive `User-Agent` with contact info.',
  '- **RainViewer** — attribution *and* the link are mandatory under their terms.',
  '- **LibreWXR** — display "Radar-DPC" whenever Italian DPC tiles are shown (CC BY-SA 4.0).',
  '- **GOES GLM** — cite NCEI DOI `10.7289/V5KH0KK6`.',
  '- **NASA** — attribution must not imply endorsement.',
  '- **CelesTrak** — 2-hour polling floor is a condition of use, not a suggestion.',
  '',
);

const content = lines.join('\n');

if (check) {
  let existing = '';
  try {
    existing = readFileSync(outPath, 'utf8');
  } catch {
    console.error('ATTRIBUTION.md is missing. Run: pnpm attribution');
    process.exit(1);
  }
  if (existing.trim() !== content.trim()) {
    console.error(
      'ATTRIBUTION.md is out of date with src/data/sources.mjs.\nRun: pnpm attribution',
    );
    process.exit(1);
  }
  console.log(`ATTRIBUTION.md is current (${attributions.length} required attributions).`);
} else {
  writeFileSync(outPath, content + '\n', 'utf8');
  console.log(
    `Wrote ATTRIBUTION.md — ${attributions.length} required attributions, ` +
      `${noAttribution.length} public-domain sources listed for provenance.`,
  );
}
