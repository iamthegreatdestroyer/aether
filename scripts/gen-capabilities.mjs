#!/usr/bin/env node
/**
 * Generate the Tauri HTTP capability allowlist FROM the endpoint contract.
 *
 * Why this script exists, written the day it was needed (2026-08-18): P6 added
 * tauri-plugin-http for the two CORS-blocked sources and hand-wrote a two-entry allowlist.
 * But the transport is GLOBAL — once armed, every fetchJson in the app goes through Rust —
 * so all twenty other sources started answering "url not allowed on the configured scope"
 * in the desktop build. The self-check only exercised the two allowed hosts, so it passed
 * while the app was broken, and that MSI shipped repeatedly.
 *
 * The lesson is the same one the contract itself encodes: a hand-maintained list of URLs
 * drifts from the code that uses them. This derives the allowlist from sources.mjs, and CI
 * runs it with --check.
 *
 *   node scripts/gen-capabilities.mjs           # write the capability file
 *   node scripts/gen-capabilities.mjs --check   # exit 1 if it is out of date
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { SOURCES } from '../src/data/sources.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, '..', 'src-tauri', 'capabilities', 'default.json');

/**
 * Hosts the app reaches that no contract entry names directly. Each needs a reason —
 * an unexplained host in a security boundary is how allowlists rot.
 */
const EXTRA_HOSTS = [
  // GOES-West sibling of the contracted noaa-goes19 bucket; src/layers/lightning.ts polls
  // both satellites (verified identical CORS and layout 2026-08-18).
  'noaa-goes18.s3.amazonaws.com',
];

const hosts = new Set(EXTRA_HOSTS);
for (const s of SOURCES) {
  for (const u of [s.baseUrl, s.probeUrl]) {
    if (!u) continue;
    try {
      hosts.add(new URL(u).host);
    } catch {
      /* a malformed URL is the probe's problem to report, not this script's */
    }
  }
}

const capability = {
  $schema: '../gen/schemas/desktop-schema.json',
  identifier: 'default',
  description:
    'Aether main window: core APIs plus native HTTP scoped to the endpoint contract. ' +
    'GENERATED by scripts/gen-capabilities.mjs — edit src/data/sources.mjs, not this file.',
  windows: ['main', 'widget'],
  permissions: [
    'core:default',
    // The main window shows/hides the widget window (the 🪟 toggle).
    'core:window:allow-show',
    'core:window:allow-hide',
    'core:window:allow-set-focus',
    // The widget raises the main window when clicked, and remembers its own size.
    'core:window:allow-unminimize',
    'core:window:allow-inner-size',
    'core:window:allow-set-size',
    'core:window:allow-outer-position',
    {
      identifier: 'http:default',
      allow: [...hosts].sort().map((h) => ({ url: `https://${h}/*` })),
    },
  ],
};

const rendered = JSON.stringify(capability, null, 2) + '\n';

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    /* missing file fails the comparison below, which is the right answer */
  }
  if (current !== rendered) {
    console.error(
      'capabilities/default.json is out of date with the endpoint contract.\n' +
        'Run: node scripts/gen-capabilities.mjs',
    );
    process.exit(1);
  }
  console.log(`capability allowlist matches the contract — ${hosts.size} hosts.`);
} else {
  writeFileSync(OUT, rendered, 'utf8');
  console.log(`Wrote ${OUT} — ${hosts.size} hosts allowed.`);
}
